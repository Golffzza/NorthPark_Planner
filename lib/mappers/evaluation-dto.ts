//* ./lib/mappers/evaluation-dto.ts

import type {
  Prisma,
  TripEvaluation,
} from "@prisma/client";

export type EvaluationDto = {
  id: string;
  tripId: string;
  weatherSnapshotId?: string | null;
  routeSnapshotId?: string | null;
  sunsetSnapshotId?: string | null;

  totalScore: number;
  level: TripEvaluation["level"];

  weatherScore: number;
  durationScore: number;
  timeScore: number;

  /**
   * Legacy field name.
   * ปัจจุบันหมายถึง transport/accessibility score
   */
  userProfileScore: number;

  canProceed?: boolean;

  factors?: Prisma.JsonValue | null;

  constraints?: Prisma.JsonValue | null;

  summary: string;
  recommendation: string;

  /**
   * Natural-language explanation generated by LLM.
   *
   * เป็น optional เพื่อรองรับ evaluation เก่าที่สร้าง
   * ก่อน feature นี้ และกรณี LLM ใช้งานไม่ได้
   */
  explanationHeadline?: string | null;
  explanationText?: string | null;

  evaluatedAt: string;
  createdAt: string;
};

export function mapEvaluationToDto(
  evaluation: TripEvaluation,
): EvaluationDto {
  return {
    id: evaluation.id,
    tripId: evaluation.tripId,
    weatherSnapshotId: evaluation.weatherSnapshotId ?? null,
    routeSnapshotId: evaluation.routeSnapshotId ?? null,
    sunsetSnapshotId: evaluation.sunsetSnapshotId ?? null,

    totalScore: evaluation.totalScore,
    level: evaluation.level,

    weatherScore:
      evaluation.weatherScore,

    durationScore:
      evaluation.durationScore,

    timeScore:
      evaluation.timeScore,

    userProfileScore:
      evaluation.userProfileScore,

    canProceed:
      evaluation.canProceed,

    factors:
      evaluation.factors,

    constraints:
      evaluation.constraints,

    summary:
      evaluation.summary,

    recommendation:
      evaluation.recommendation,

    explanationHeadline:
      evaluation.explanationHeadline,

    explanationText:
      evaluation.explanationText,

    evaluatedAt:
      evaluation.evaluatedAt.toISOString(),

    createdAt:
      evaluation.createdAt.toISOString(),
  };
}
