        "5. ปิดท้ายด้วยสิ่งที่ควรทำต่อจาก engineRecommendation หรือ constraints เท่านั้น",
        "",
        "ข้อห้ามสำคัญ:",
        "- ห้ามคำนวณคะแนนใหม่",
        "- ห้ามสร้าง action ใหม่จาก factor reason",
        "- ห้ามเพิ่มข้อมูลที่ไม่มีใน input",
        "- ห้ามตีความคะแนนเป็นเปอร์เซ็นต์ความปลอดภัย",
        "- ห้ามเพิ่มคำแนะนำเรื่องถนน ข่าว ประกาศ หรือเส้นทาง ถ้าไม่มีในข้อมูล",
